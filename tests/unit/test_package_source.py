import hashlib
import json
import zipfile

import pytest

from scripts.package_source import ARCHIVE_ROOT, source_files, verify_source_archive
from vqa_explanation.utils.run_provenance import source_fingerprints


def _minimum_source(root):
    for name in (
        "pyproject.toml",
        "requirements.txt",
        "scripts/run_pipeline.py",
        "src/vqa_explanation/__init__.py",
    ):
        path = root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(name, encoding="utf-8")


def test_source_files_include_every_provenance_fingerprint_and_yml_config(tmp_path):
    _minimum_source(tmp_path)
    yml = tmp_path / "configs/experiment.yml"
    yml.parent.mkdir(parents=True)
    yml.write_text("seed: 42\n", encoding="utf-8")
    selected = {path.relative_to(tmp_path).as_posix() for path in source_files(tmp_path)}
    assert set(source_fingerprints(tmp_path)) <= selected
    assert "configs/experiment.yml" in selected
    hidden = tmp_path / "scripts/.private/notes.py"
    hidden.parent.mkdir(parents=True)
    hidden.write_text("pass\n", encoding="utf-8")
    with pytest.raises(ValueError, match="Provenance source is excluded"):
        source_files(tmp_path)


@pytest.mark.parametrize("filename", ["secrets.yaml", "secrets-prod.yaml", "api_keys.local.yml"])
def test_source_files_refuse_credential_named_configs(tmp_path, filename):
    _minimum_source(tmp_path)
    secret = tmp_path / "configs" / filename
    secret.parent.mkdir(parents=True)
    secret.write_text("api_key: do-not-package\n", encoding="utf-8")
    with pytest.raises(ValueError, match="credential-like"):
        source_files(tmp_path)


def test_archive_verifier_checks_exact_member_set_and_bytes(tmp_path):
    content = b"print('ok')\n"
    relative = "scripts/run_pipeline.py"
    manifest = {relative: hashlib.sha256(content).hexdigest()}
    archive_path = tmp_path / "source.zip"
    with zipfile.ZipFile(archive_path, "x") as archive:
        archive.writestr(ARCHIVE_ROOT + relative, content)
        archive.writestr(ARCHIVE_ROOT + "SOURCE_MANIFEST.json", json.dumps(manifest))
    verify_source_archive(archive_path, manifest)
    with zipfile.ZipFile(archive_path, "a") as archive:
        archive.writestr(ARCHIVE_ROOT + "unexpected.py", b"pass\n")
    with pytest.raises(ValueError, match="members"):
        verify_source_archive(archive_path, manifest)


def test_archive_verifier_rejects_manifest_hash_mismatch(tmp_path):
    relative = "scripts/run_pipeline.py"
    manifest = {relative: hashlib.sha256(b"original").hexdigest()}
    archive_path = tmp_path / "source.zip"
    with zipfile.ZipFile(archive_path, "x") as archive:
        archive.writestr(ARCHIVE_ROOT + relative, b"changed")
        archive.writestr(ARCHIVE_ROOT + "SOURCE_MANIFEST.json", json.dumps(manifest))
    with pytest.raises(ValueError, match="hash mismatch"):
        verify_source_archive(archive_path, manifest)


def test_source_includes_only_allowlisted_small_sample_jsonl(tmp_path):
    _minimum_source(tmp_path)
    for name in ("vivqax_sample.jsonl", "preference_sample.jsonl", "not_allowed.jsonl"):
        path = tmp_path / "data/sample" / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text('{}\n', encoding="utf-8")
    full = tmp_path / "data/processed/all.jsonl"
    full.parent.mkdir(parents=True)
    full.write_text('{}\n', encoding="utf-8")
    selected = {path.relative_to(tmp_path).as_posix() for path in source_files(tmp_path)}
    assert "data/sample/vivqax_sample.jsonl" in selected
    assert "data/sample/preference_sample.jsonl" in selected
    assert "data/sample/not_allowed.jsonl" not in selected
    assert "data/processed/all.jsonl" not in selected


def test_source_excludes_generated_install_metadata(tmp_path):
    _minimum_source(tmp_path)
    generated = tmp_path / "src/project.egg-info/SOURCES.txt"
    generated.parent.mkdir(parents=True)
    generated.write_text("regenerated by pip", encoding="utf-8")
    selected = {path.relative_to(tmp_path).as_posix() for path in source_files(tmp_path)}
    assert "src/project.egg-info/SOURCES.txt" not in selected


def test_executed_notebook_evidence_is_not_in_source_release(tmp_path):
    _minimum_source(tmp_path)
    evidence = tmp_path / "notebooks/archive/03_m1_with_outputs_20261013.ipynb"
    evidence.parent.mkdir(parents=True)
    evidence.write_text('{"cells": []}', encoding="utf-8")
    selected = {path.relative_to(tmp_path).as_posix() for path in source_files(tmp_path)}
    assert evidence.relative_to(tmp_path).as_posix() not in selected
